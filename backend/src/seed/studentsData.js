/**
 * Helper to get clean normalized identifiers
 */
export const formatStudentInfo = (item) => {
  const parts = item.regNo.split('/');
  // Expected formats:
  // "SEU/IS/22/ICT/001" -> year: "22", code: "ICT", num: "001"
  // "SEU/IS/21/ICT/064" -> year: "21", code: "ICT", num: "064"
  const year = parts[2] || '22';
  const code = parts[3] || 'ICT';
  const num = parts[4] || String(item.sn).padStart(3, '0');

  const shortReg = `${year}${code}${num}`;
  const indexNumber = `${code}${year}${num}`;
  const email = `${year}${code.toLowerCase()}${num}@seu.ac.lk`;
  const isRepeat = year === '21';

  return {
    ...item,
    year,
    code,
    num,
    shortReg,
    indexNumber,
    email,
    isRepeat,
    semester: isRepeat ? 7 : 5,
    academicYear: '2025/2026',
    batch: isRepeat ? '2021/2022' : '2022/2023',
    degreeProgramme: 'BICT',
    department: 'Department of Information and Communication Technology'
  };
};
